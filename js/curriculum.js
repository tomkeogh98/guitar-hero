const pick = (v, guitar) => (v && typeof v === "object" ? (guitar === "acoustic" ? v.a : v.e) : v);

// The tempo a block's own instructions ask for ("at 60 bpm", "metronome to 40"), else the lesson default.
function bpmFrom(text, fallback) {
  const m = /(\d{2,3})\s*bpm/i.exec(text || "") || /metronome to (\d{2,3})/i.exec(text || "");
  return m ? Number(m[1]) : fallback;
}

export function getLesson(index, guitar = "electric") {
  const round = Math.floor(index / LESSON_COUNT);
  const i = index % LESSON_COUNT;
  const weekIdx = Math.floor(i / 5);
  const dayIdx = i % 5;
  const week = WEEKS[weekIdx];
  const day = week.days[dayIdx];
  const bump = round * 10;
  const blocks = {
    w: pick(day.w, guitar),
    x: pick(day.x, guitar),
    r: pick(day.r, guitar),
    f: pick(day.f, guitar),
    s: pick(day.s, guitar),
    rec: pick(day.rec, guitar),
    free: FREE_PLAY[index % FREE_PLAY.length],
  };
  const mins = Object.fromEntries(BLOCKS.map((b) => [b.key, day.m?.[b.key] ?? b.mins]));
  const bpm = Object.fromEntries(BLOCKS.map((b) => [b.key, bpmFrom(blocks[b.key], day.bpm) + bump]));
  return {
    index,
    round: round + 1,
    week: weekIdx + 1,
    day: dayIdx + 1,
    weekTitle: week.title,
    title: day.t,
    buildsOn: dayIdx === 0 ? week.buildsOn : day.b,
    areas: week.areas,
    bpm: day.bpm + bump,
    bpmFor: bpm,
    mins,
    recSecs: day.recSecs || 90,
    tab: day.tab || null,
    tone: pick(week.tone, guitar),
    blocks,
  };
}

export function lessonLabel(index) {
  const l = getLesson(index);
  return `${l.round > 1 ? `Round ${l.round} · ` : ""}Week ${l.week} · Day ${l.day}`;
}
