// 13 weeks x 5 = 65 lessons. Past the end, lessons cycle back as "Round 2" with tempos raised.
export const LESSON_COUNT = WEEKS.length * 5;

export const FREE_PLAY = [
  "Noodle over a backing track in A minor. No rules.",
  "Play the song you'd most like to be able to play, even badly.",
  "Write down a riff idea you'd like to come back to.",
  "Play the slowest, most expressive melody you can.",
  "Pick a song from the radio and work out the chords by ear.",
  "Make up a riff using only two strings.",
  "Play anything you like with your eyes closed.",
  "Revisit a song from an earlier week, just for fun.",
];

const pick = (v, guitar) => (v && typeof v === "object" ? (guitar === "acoustic" ? v.a : v.e) : v);

export function getLesson(index, guitar = "electric") {
  const round = Math.floor(index / LESSON_COUNT);
  const i = index % LESSON_COUNT;
  const weekIdx = Math.floor(i / 5);
  const dayIdx = i % 5;
  const week = WEEKS[weekIdx];
  const day = week.days[dayIdx];
  const bump = round * 10;
  return {
    index,
    round: round + 1,
    week: weekIdx + 1,
    day: dayIdx + 1,
    weekTitle: week.title,
    title: day.t,
    buildsOn: dayIdx === 0 ? week.buildsOn : day.b,
    areas: week.areas,
    bpm: day.bpm + bump,
    tab: day.tab || null,
    tone: pick(week.tone, guitar),
    blocks: {
      w: pick(day.w, guitar),
      x: pick(day.x, guitar),
      r: pick(day.r, guitar),
      f: pick(day.f, guitar),
      s: pick(day.s, guitar),
      rec: pick(day.rec, guitar),
      free: FREE_PLAY[index % FREE_PLAY.length],
    },
  };
}

export function lessonLabel(index) {
  const l = getLesson(index);
  return `${l.round > 1 ? `Round ${l.round} · ` : ""}Week ${l.week} · Day ${l.day}`;
}
